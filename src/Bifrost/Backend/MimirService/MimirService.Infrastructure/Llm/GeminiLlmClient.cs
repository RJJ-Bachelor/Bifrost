using System.Net.Http.Json;
using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using MimirService.Application.Services.Llm;

namespace MimirService.Infrastructure.Llm;

internal sealed class GeminiLlmClient(
    HttpClient httpClient,
    IOptions<GeminiOptions> options,
    ILogger<GeminiLlmClient> logger) : ILlmClient
{
    private static readonly JsonSerializerOptions SerializerOptions = new(JsonSerializerDefaults.Web)
    {
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
    };

    public async Task<string> GenerateAsync(
        string systemInstruction,
        string prompt,
        JsonElement responseSchema,
        CancellationToken cancellationToken)
    {
        var responseFormat = new ResponseFormatConfig(new TextResponseFormat("APPLICATION_JSON", responseSchema));

        foreach (var model in options.Value.Models)
        {
            try
            {
                var text = await RequestModelAsync(model, systemInstruction, prompt, responseFormat, cancellationToken);
                if (!string.IsNullOrWhiteSpace(text))
                {
                    // A malformed JSON answer throws JsonException, so the next model is tried.
                    JsonDocument.Parse(text).Dispose();

                    logger.LogInformation("LLM response generated by {Model}.", model);
                    return text;
                }

                logger.LogWarning("Model {Model} returned an empty response. Trying next model.", model);
            }
            catch (Exception exception) when (
                exception is HttpRequestException or JsonException
                || (exception is TaskCanceledException && !cancellationToken.IsCancellationRequested))
            {
                logger.LogWarning(exception, "Model {Model} failed. Trying next model.", model);
            }
        }

        throw new LlmUnavailableException("All configured LLM models failed.");
    }

    private async Task<string?> RequestModelAsync(
        string model,
        string systemInstruction,
        string prompt,
        ResponseFormatConfig responseFormat,
        CancellationToken cancellationToken)
    {
        var body = new GenerateContentRequest(
            Contents: [new Content([new Part(prompt)], Role: "user")],
            SystemInstruction: new Content([new Part(systemInstruction)]),
            GenerationConfig: new GenerationConfig(options.Value.Temperature, responseFormat));

        using var request = new HttpRequestMessage(
            HttpMethod.Post,
            $"v1beta/models/{Uri.EscapeDataString(model)}:generateContent");
        request.Headers.Add("x-goog-api-key", options.Value.ApiKey);
        request.Content = JsonContent.Create(body, options: SerializerOptions);

        using var response = await httpClient.SendAsync(request, cancellationToken);
        if (!response.IsSuccessStatusCode)
        {
            var error = await response.Content.ReadAsStringAsync(cancellationToken);
            throw new HttpRequestException(
                $"Model {model} returned {(int)response.StatusCode}: {error}",
                inner: null,
                response.StatusCode);
        }

        var result = await response.Content.ReadFromJsonAsync<GenerateContentResponse>(
            SerializerOptions, cancellationToken);

        // Thinking models return thought parts before the actual answer.
        var parts = result?.Candidates?.FirstOrDefault()?.Content?.Parts ?? [];
        return parts.FirstOrDefault(part => part.Thought != true)?.Text?.Trim();
    }

    private sealed record GenerateContentRequest(
        Content[] Contents,
        Content SystemInstruction,
        GenerationConfig GenerationConfig);

    private sealed record Content(Part[]? Parts, string? Role = null);

    private sealed record Part(string? Text, bool? Thought = null);

    private sealed record GenerationConfig(double Temperature, ResponseFormatConfig ResponseFormat);

    private sealed record ResponseFormatConfig(TextResponseFormat Text);

    private sealed record TextResponseFormat(string MimeType, JsonElement Schema);

    private sealed record GenerateContentResponse(Candidate[]? Candidates);

    private sealed record Candidate(Content? Content);
}
